/// Simulator card showing child device generating and displaying pairing code.
final class ChildDeviceSimulatorCard extends StatelessWidget {
  const ChildDeviceSimulatorCard({required this.controller, super.key});
  final PairingSimulationController controller;

  @override
  Widget build(BuildContext context) {
    return SectionCard(
      title: 'Step 1: Child Device (Simulated)',
      subtitle: 'The child device requests a 6-digit pairing code.',
      child: Obx(() {
        final session = controller.session.value;
        if (session == null) {
          return Center(
            child: HavenButton(
              label: 'Generate 6-Digit Code',
              onPressed: controller.generateCode,
            ),
          );
        }
        return Column(
          children: [
            Container(
              padding: const EdgeInsets.symmetric(
                vertical: HavenSpacing.md,
                horizontal: HavenSpacing.lg,
              ),
              decoration: BoxDecoration(
                color: Theme.of(context).colorScheme.surfaceContainerHighest,
                borderRadius: BorderRadius.circular(12),
              ),
              child: Text(
                '${session.code.substring(0, 3)} ${session.code.substring(3)}',
                style: const TextStyle(
                  fontSize: 32,
                  fontWeight: FontWeight.bold,
                  letterSpacing: 4.0,
                ),
              ),
            ),
            const SizedBox(height: HavenSpacing.sm),
            Row(
              mainAxisAlignment: MainAxisAlignment.center,
              children: [
                const Icon(Icons.timer_outlined, size: 16),
                const SizedBox(width: 4),
                Text(
                  session.isExpired
                      ? 'Expired'
                      : 'Expires in ${controller.remainingTimeString}',
                  style: HavenText.caption.copyWith(
                    color: session.isExpired
                        ? Theme.of(context).colorScheme.error
                        : null,
                  ),
                ),
              ],
            ),
          ],
        );
      }),
    );
  }
}

/// Form card for parent entering pairing code and associating child.
final class ParentEntryFormCard extends StatelessWidget {
  const ParentEntryFormCard({required this.controller, super.key});
  final PairingSimulationController controller;

  @override
  Widget build(BuildContext context) {
    return SectionCard(
      title: 'Step 2: Parent Entry & Pairing',
      subtitle: 'Select the child and enter the 6-digit code shown above.',
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          Obx(() {
            if (controller.children.isEmpty) {
              return const Text('No children found in this family.');
            }
            return DropdownButtonFormField(
              decoration: const InputDecoration(labelText: 'Associate with Child'),
              initialValue: controller.selectedChild.value,
              items: controller.children
                  .map((c) => DropdownMenuItem(value: c, child: Text(c.name)))
                  .toList(),
              onChanged: (val) {
                if (val != null) controller.selectChild(val);
              },
            );
          }),
          const SizedBox(height: HavenSpacing.sm),
          HavenField(
            label: 'Enter 6-Digit Code',
            controller: controller.codeController,
            keyboardType: TextInputType.number,
            maxLength: 6,
            helper: 'Enter the code generated by the child device',
          ),
          Obx(() {
            final err = controller.errorMessage.value;
            if (err == null) return const SizedBox.shrink();
            return Padding(
              padding: const EdgeInsets.only(bottom: HavenSpacing.sm),
              child: Text(
                err,
                style: TextStyle(color: Theme.of(context).colorScheme.error),
              ),
            );
          }),
          Row(
            children: [
              Expanded(
                child: HavenButton(
                  label: 'Pair Device',
                  busy: controller.isSubmitting.value,
                  onPressed: controller.submitCode,
                ),
              ),
              const SizedBox(width: HavenSpacing.sm),
              HavenButton(
                label: 'Cancel',
                primary: false,
                onPressed: controller.cancelSimulation,
              ),
            ],
          ),
        ],
      ),
    );
  }
}
